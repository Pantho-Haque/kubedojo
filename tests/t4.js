const { PG, sim, run, stop, sh } = require('./harness.js');
(async () => {
  await run(`kind create cluster --name lab`, false);
  await run('kubectl create namespace web', false);
  await run('helm2 ls');
  await run('helm2 init --client-only');
  await run('kubectl -n kube-system create serviceaccount tiller');
  await run('helm2 init --service-account tiller --tiller-image ghcr.io/helm/tiller:v2.17.0 --stable-repo-url https://charts.helm.sh/stable');
  await run('kubectl -n kube-system rollout status deploy/tiller-deploy');
  await run('kubectl create clusterrolebinding tiller --clusterrole=cluster-admin --serviceaccount=kube-system:tiller');
  await run('helm2 version --short');
  await run('helm2 lint myapp');
  await run('helm2 template myapp --name demo --namespace web -x templates/service.yaml');
  await run('helm2 template myapp --name demo --namespace web --set replicaCount=3,ingress.enabled=true | grep -E "replicas|kind:|host:"');
  await run('helm2 install myapp --name demo --namespace web --wait --timeout 120');
  await run('helm2 ls');
  await run('kubectl get all -n web -l app.kubernetes.io/instance=demo');
  await run('helm2 test demo');
  await run('helm2 upgrade demo myapp --namespace web --set replicaCount=3 --set image.tag=1.27.1 --wait --timeout 300');
  await run('helm2 history demo');
  await run('kubectl get pods -n web');
  await run('helm2 rollback demo 1');
  await run('helm2 get values demo');
  await run('kubectl get cm -n kube-system -l OWNER=TILLER');
  await run('helm2 upgrade demo myapp --namespace web --set image.tag=doesnotexist.nope.local/x --set migration.enabled=true', false);
  await run('helm2 delete demo --purge');
  await run('kubectl get all -n web');
  stop();
})().catch(e => { console.error(e); process.exit(1); });
