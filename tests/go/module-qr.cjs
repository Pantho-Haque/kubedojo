'use strict';
// Loads the <script id="modules"> block from gothik.html.
const vm = require('node:vm');
const { block } = require('./_html.cjs');
let mods = null;
// same realm as the tests, so deepStrictEqual sees ordinary objects
const loadModules = () => { if (!mods) { vm.runInThisContext(block('modules')); mods = globalThis; } return mods; };
const test = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const QR = loadModules().GothikQR;

const rows = (m) => m.modules.map((r) => r.join(''));

test('matches Nayuki qrcodegen reference (v2-M, mask 3)', () => {
  // Generated by python qrcodegen: encode_segments([make_bytes(b'https://gothik.dev/')], MEDIUM, 2, 2, 3, False)
  const ref = ['1111111011010010101111111', '1000001011011100101000001', '1011101001001100001011101', '1011101010011101001011101', '1011101001011111101011101', '1000001000110010101000001', '1111111010101010101111111', '0000000010100000100000000', '1011011101000100101001011', '0101110100111100100100010', '1111001100110100001100000', '1100000110100001011001100', '1000111000001010011010111', '0010110111011011001110001', '0100111100110100010010110', '1010100101110010001110001', '0011101000101011111111111', '0000000010000010100010101', '1111111011000110101010111', '1000001010010111100010001', '1011101001000110111111000', '1011101010000000011011111', '1011101010000010111010110', '1000001000011110001010100', '1111111010110000001111111'];
  assert.deepEqual(rows(QR.matrix('https://gothik.dev/', { ecc: 'M', mask: 3 })), ref);
});

test('matches reference on a v17-L code with version info (hash)', () => {
  const m = QR.matrix('https://gothik.dev/#s=' + 'x'.repeat(600), { ecc: 'L', mask: 4 });
  assert.equal(m.version, 17);
  const h = crypto.createHash('sha256').update(rows(m).join('')).digest('hex');
  assert.equal(h, '4f42dbcaa70fdac29ff806a4056888b956a5cb123a31f8d8d070f3afa0964c27');
});

test('picks the smallest version and respects capacity', () => {
  assert.equal(QR.matrix('a'.repeat(17), { ecc: 'L' }).version, 1);
  assert.equal(QR.matrix('a'.repeat(18), { ecc: 'L' }).version, 2);
  assert.equal(QR.matrix('a'.repeat(14), { ecc: 'M' }).version, 1);
  assert.equal(QR.matrix('a'.repeat(15), { ecc: 'M' }).version, 2);
  assert.deepEqual(['L', 'M', 'Q', 'H'].map(QR.capacity), [2953, 2331, 1663, 1273]);
  assert.equal(QR.matrix('a'.repeat(2331), { ecc: 'M' }).version, 40);
  assert.throws(() => QR.matrix('a'.repeat(2332), { ecc: 'M' }), /at most 2331 bytes/);
  assert.equal(QR.matrix('a'.repeat(2500), { ecc: 'L' }).version, 37); // v37-L holds 2520 bytes
  assert.equal(QR.matrix('é'.repeat(8), { ecc: 'L' }).version, 1); // 16 UTF-8 bytes
  assert.equal(QR.matrix('é'.repeat(9), { ecc: 'L' }).version, 2); // 18 UTF-8 bytes
});

test('finder patterns, dark module and default ecc', () => {
  const m = QR.matrix('hello');
  assert.equal(m.ecc, 'M');
  assert.equal(m.size, 21);
  const s = m.size, f = ['1111111', '1000001', '1011101', '1011101', '1011101', '1000001', '1111111'];
  for (let i = 0; i < 7; i++) {
    assert.equal(m.modules[i].slice(0, 7).join(''), f[i]);
    assert.equal(m.modules[i].slice(s - 7).join(''), f[i]);
    assert.equal(m.modules[s - 7 + i].slice(0, 7).join(''), f[i]);
  }
  assert.equal(m.modules[s - 8][8], 1);
});

test('svg output', () => {
  const svg = QR.svg('hello', { ecc: 'L', border: 2 });
  assert.match(svg, /^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" viewBox="0 0 25 25" shape-rendering="crispEdges"><path fill="currentColor" d="M2 2h7v1h-7z/);
  assert.ok(!/<rect/.test(svg));
  // Dark-module count in path equals the matrix's.
  const dark = QR.matrix('hello', { ecc: 'L' }).modules.flat().reduce((a, b) => a + b, 0);
  const drawn = [...svg.matchAll(/h(\d+)v1/g)].reduce((a, x) => a + +x[1], 0);
  assert.equal(drawn, dark);
  assert.throws(() => QR.svg('x'.repeat(3000), { ecc: 'L' }), /GothikQR: text is 3000 bytes/);
  assert.throws(() => QR.svg('x', { ecc: 'Z' }), /unknown ecc/);
});

test('deterministic and frozen global', () => {
  assert.deepEqual(QR.matrix('same'), QR.matrix('same'));
  assert.ok(Object.isFrozen(globalThis.GothikQR));
});
