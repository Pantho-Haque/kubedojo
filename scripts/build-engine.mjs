// Concatenates the simulator engine parts (src/engine/parts/NN_*.js, in order) into
//   src/engine/engine.js   an ES module (default export: PG) used by the React app
//   tests/.engine.cjs      the same code as strict CommonJS for the Node scenario tests
// The parts are the original, framework-free simulator: shell, virtual FS, cluster controllers,
// kind/k3d/docker/kubectl/helm 2 commands, vi, export-script generator, guide data, Tab completion.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src/engine/parts');
const parts = readdirSync(dir).filter(f => /^\d\d_.*\.js$/.test(f)).sort();
const code = parts.map(f => readFileSync(join(dir, f), 'utf8')).join('\n');
const banner = '/* GENERATED by scripts/build-engine.mjs from src/engine/parts/*.js — do not edit */\n';
const esm = code.replace(/^if \(typeof module !== 'undefined'\) module\.exports = PG;$/gm, ''); // the CommonJS export lines are only for the Node tests
writeFileSync(join(root, 'src/engine/engine.js'), banner + esm + '\nexport default PG;\n');
writeFileSync(join(root, 'tests/.engine.cjs'), banner + "'use strict';\n" + code + '\n');
console.log(`engine: ${parts.length} parts, ${Math.round(code.length / 1024)} KB`);
